def m(key: str, value: Any, fmt: str = "{:.3f}") -> str:
    if isinstance(value, str):
        s = value
    elif value is None or (isinstance(value, float) and not np.isfinite(value)):
        s = "n/a"
    elif isinstance(value, (int, np.integer)):
        s = f"{int(value):,}".replace(",", "{,}")
    else:
        s = fmt.format(value)
    s = typeset_numbers(s)
    MACROS[key] = s
    return s


def pm(d: Dict[str, float], fmt="{:.3f}") -> str:
    if d["n"] == 0:
        return "--"
    return f"{fmt.format(d['mean'])} $\\pm$ {fmt.format(d['sd'])}"


def ci(lo, hi, fmt="{:+.3f}") -> str:
    return f"[{fmt.format(lo)}, {fmt.format(hi)}]"


def pval(p: float) -> str:
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


_MINUS = re.compile(r"(?<![\w\-{^])-(?=\d)")
_NEG_ZERO = re.compile(r"(?<![\w\-{^])-(?=0\.0+(?!\d))")


def typeset_numbers(s: str) -> str:
    """Typographic minus for negative numbers in text mode; drop the sign of rounded zeros (-0.00)."""
    s = _NEG_ZERO.sub("", s)
    return _MINUS.sub(r"\\textminus{}", s)


def tex_text(s: str) -> str:
    """Escape free text (justifications, labels) for LaTeX."""
    s = s.replace("\\", "\\textbackslash{}")
    for ch in ("%", "&", "#", "_"):
        s = s.replace(ch, "\\" + ch)
    return s.replace("<=", "$\\leq$").replace(">=", "$\\geq$")


def write(name: str, body: str) -> None:
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write("% Generated by experiments/reporting/export_latex.py -- do not edit.\n" + body)


def table(label: str, caption: str, colspec: str, header: str, rows: List[str], note: str, size: str = "\\scriptsize") -> str:
    return (
        "\\begin{table}[H]\n\\centering\n" + size + "\n\\setlength{\\tabcolsep}{3pt}\n"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n"
        f"\\begin{{tabularx}}{{\\textwidth}}{{{colspec}}}\n\\toprule\n{header} \\\\\n\\midrule\n"
        + " \\\\\n".join(typeset_numbers(r) for r in rows) + " \\\\\n\\bottomrule\n\\end{tabularx}\n"
        f"\\par\\smallskip\\raggedright\\footnotesize\\textit{{Source: Authors' own work.}} {note}\n\\end{{table}}\n"
    )


