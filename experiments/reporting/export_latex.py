def overhead_section(ds: str, truns) -> Dict[str, Any]:
    out = {}
    for cfg in ["E1", "E2_s4", "E3", "E4"] + [f"E3_topk{k}" for k in TOPK] + [f"E1_topk{k}" for k in TOPK]:
        r = truns.get(cfg, {})
        if not r:
            continue
        g = lambda key: describe(list(metric_by_seed(r, perf(key)).values()))
        out[cfg] = {
            "uplink_mb": g("uplink_bytes"), "down_model_mb": g("downlink_model_bytes"),
            "down_mask_mb": g("downlink_mask_bytes"), "down_ctx_mb": g("downlink_he_context_bytes"),
            "agg_s": g("aggregation_time_sec"), "enc_s": g("he_encryption_time_sec"),
            "hecomp_s": g("he_computation_time_sec"), "dec_s": g("he_decryption_time_sec"),
            "keygen_s": g("he_keygen_time_sec"), "local_s": g("local_training_time_sec"),
            "sparsify_s": g("sparsification_time_sec"), "total_s": g("total_training_time_sec"),
            "n": len(r),
        }
        for k in ("uplink_mb", "down_model_mb", "down_mask_mb", "down_ctx_mb"):
            for f in ("mean", "sd", "ci_lo", "ci_hi"):
                out[cfg][k][f] = out[cfg][k][f] / 1024 ** 2
    return out


