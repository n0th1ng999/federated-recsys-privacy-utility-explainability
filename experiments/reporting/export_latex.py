def attack_section(runs, recon) -> Dict[str, Any]:
    out = {"mia": {}, "dlg": {}}
    for cfg in MAIN_CONFIGS:
        r = runs.get(cfg, {})
        if not r:
            continue
        def g(unit, key):
            return [v["membership_inference"][unit][key] for v in r.values()]
        cl, rcd = "client_participation", "record_membership"
        out["mia"][cfg] = {
            "client_auc": describe(g(cl, "auc")), "client_sig": int(np.sum(np.asarray(g(cl, "auc_permutation_p")) < 0.05)),
            "client_tpr10": describe(g(cl, "tpr_at_fpr_0.1")), "client_adv": describe(g(cl, "advantage_max_tpr_minus_fpr")),
            "record_auc": describe(g(rcd, "auc")), "record_sig": int(np.sum(np.asarray(g(rcd, "auc_permutation_p")) < 0.05)),
            "record_tpr01": describe(g(rcd, "tpr_at_fpr_0.01")),
            "record_auc_below_half_sig": int(np.sum((np.asarray(g(rcd, "auc")) < 0.5) & (np.asarray(g(rcd, "auc_permutation_p")) < 0.05))),
            "client_n_members": int(np.mean(g(cl, "n_members"))), "client_n_non": int(np.mean(g(cl, "n_nonmembers"))),
            "record_n_members": int(np.mean(g(rcd, "n_members"))), "record_n_non": int(np.mean(g(rcd, "n_nonmembers"))),
            "n": len(r),
        }
    if recon:
        names = list(next(iter(recon.values()))["scenarios"])
        for s in names:
            cos = [v["scenarios"][s]["mean_cos_std"] for v in recon.values()]
            succ = [v["scenarios"][s]["success_rate"] for v in recon.values()]
            mse = [v["scenarios"][s]["mse_relative_to_prior_guess"] for v in recon.values()]
            out["dlg"][s] = {"cos": describe(cos), "success": describe(succ), "mse_rel": describe(mse), "n": len(cos)}
        out["dlg_params"] = next(iter(recon.values()))["params"]
        out["dlg_records"] = next(iter(recon.values()))["n_records"]
    return out


