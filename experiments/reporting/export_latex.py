def mcda_section(u, x, c) -> Dict[str, Any]:
    archs = ["E0", "E1", "E2", "E3", "E3_topk10", "E4"]
    cfg_of = {"E0": "E0", "E1": "E1", "E2": "E2_s4", "E3": "E3", "E3_topk10": "E3_topk10", "E4": "E4"}
    # Risk-adjusted utility: lower end of the 95% t-interval of mean nDCG@10 over seeds, so that
    # between-seed variability (large under DP noise) is not rewarded as if it were utility.
    ndcg = {}
    for a in archs:
        if a == "E3_topk10":
            ndcg[a] = SUMMARY["topk"]["10"]["he_ndcg"]["ci_lo"]
        else:
            ndcg[a] = u["ears"][cfg_of[a]]["ndcg"]["ci_lo"]
    fid = {a: x[cfg_of[a]]["gap_cond"]["mean"] if cfg_of[a] in x else x["E3"]["gap_cond"]["mean"] for a in archs}
    eps = {a: (u["ears"][cfg_of[a]]["eps"] if cfg_of[a] in u["ears"] else None) for a in archs}
    cost = {a: c[a]["usd_operator_total"] for a in archs}
    scores = dict(JUDGEMENT_SCORES)
    scores.update(derived_scores(ndcg, u["ears"]["random"]["ndcg"]["mean"], u["ears"]["popularity"]["ndcg"]["mean"], cost, fid, eps))
    sens = sensitivity(scores, archs)
    return {"archs": archs, "scores": scores, "inputs": {"ndcg": ndcg, "fidelity_gap": fid, "epsilon": eps, "cost": cost},
            "sensitivity": sens, "weights": PERSONAS, "justification": MCDA_JUSTIFICATION}


