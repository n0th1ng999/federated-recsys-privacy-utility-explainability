def utility_section(ds: str, runs, baselines) -> Dict[str, Any]:
    out = {}
    e1 = metric_by_seed(runs.get("E1", {}), rec("ndcg@10"))
    for cfg in MAIN_CONFIGS:
        r = runs.get(cfg, {})
        nd = metric_by_seed(r, rec("ndcg@10"))
        rc = metric_by_seed(r, rec("recall@10"))
        hr = metric_by_seed(r, rec("hit_rate@10"))
        eps = metric_by_seed(r, perf("dp_epsilon"))
        cmp_ = paired(e1, nd, margin=EQUIV_MARGIN if cfg == "E3" else None) if cfg != "E1" else None
        out[cfg] = {"ndcg": describe(list(nd.values())), "recall": describe(list(rc.values())),
                    "hit": describe(list(hr.values())), "eps": float(np.mean(list(eps.values()))) if eps else None,
                    "vs_E1": cmp_, "n": len(nd)}
    rnd = [b["random"]["ndcg@10"] for b in baselines.values()]
    pop = [b["popularity_pre_cutoff"]["ndcg@10"] for b in baselines.values()]
    out["random"] = {"ndcg": describe(rnd), "recall": describe([b["random"]["recall@10"] for b in baselines.values()])}
    out["popularity"] = {"ndcg": describe(pop), "recall": describe([b["popularity_pre_cutoff"]["recall@10"] for b in baselines.values()])}
    controls = load_subdir(RESULTS, ds, "controls")
    if controls:
        out["untrained"] = {"ndcg": describe([c["untrained"]["ndcg@10"] for c in controls.values()]),
                            "recall": describe([c["untrained"]["recall@10"] for c in controls.values()])}
        out["noise_only"] = {}
        for key in next(iter(controls.values()))["noise_only"]:
            by_seed = {sd: c["noise_only"][key]["ndcg@10"] for sd, c in controls.items()}
            cfg = "E2_" + key
            out["noise_only"][key] = {
                "ndcg": describe(list(by_seed.values())),
                "recall": describe([c["noise_only"][key]["recall@10"] for c in controls.values()]),
                "noise_norm_per_round": next(iter(controls.values()))["noise_only"][key]["noise_norm_per_round"],
                "dp_vs_noise": paired(by_seed, metric_by_seed(runs.get(cfg, {}), rec("ndcg@10"))),
            }
        s4 = {sd: c["noise_only"]["s4"]["ndcg@10"] for sd, c in controls.items()}
        out["noise_only"]["s4"]["e4_vs_noise"] = paired(s4, metric_by_seed(runs.get("E4", {}), rec("ndcg@10")))
        untrained = {sd: c["untrained"]["ndcg@10"] for sd, c in controls.items()}
        out["E1_vs_untrained"] = paired(untrained, e1)
        out["num_parameters"] = next(iter(controls.values()))["num_parameters"]
    pop_by_seed = {s: b["popularity_pre_cutoff"]["ndcg@10"] for s, b in baselines.items()}
    out["E1_vs_popularity"] = paired(pop_by_seed, e1)
    # split description (identical structure for every seed)
    any_run = next(iter(next(iter(runs.values())).values()))
    out["split_example"] = any_run["provenance"]["split"]
    pos = [next(iter(r.values()))["provenance"]["split"]["num_eval_positives"] for r in [runs["E1"]]]
    out["eval_positives_by_seed"] = {s: v["provenance"]["split"]["num_eval_positives"] for s, v in runs["E1"].items()}
    return out


